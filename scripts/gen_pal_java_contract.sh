#!/usr/bin/env bash
# Generate the Java contract that the pinned crypto PAL expects.
#
# The CoreCLR-on-Android crypto PAL resolves three Java classes by name and then
# looks their members up by JNI descriptor during JNI_OnLoad. If a descriptor is
# missing it does not throw -- it aborts the whole game process:
#
#   Abort message: '.../pal_jni.c:619 (GetMethod): method <init> (J)V was not found'
#   signal 6 (SIGABRT) ... libfusion.so (dotnet_start_runtime())
#
# That descriptor is a property of the runtime pack, not of this repository, and
# it is not stable across .NET releases. Measured with javap on both jars:
#
#   .NET 11.0.0-rc.1                     .NET 10.0.12
#   <init>(J X509TrustManager String)V   <init>(J)V
#   verifyRemoteCertificate(J String)Z   verifyRemoteCertificate(J)Z
#
# Because it moves with the runtime, the expectation belongs to a generated file
# beside the runtime pin rather than to a literal inside a check. That is the same
# arrangement as provenance/sha256sums.txt, and it is the third time this tree has
# had to move a hardcoded expectation out of a script after a runtime bump (the
# others: the tfm in package_bepinex_android.sh, and EXPECTED_TFM in stage 6).
#
# The output is consumed by launcher/scripts/verify_crypto_java.sh, which compares
# it against the Java sources under launcher/app/src/main/java.
#
# Usage: gen_pal_java_contract.sh <path-to-pack.jar> [out-file]
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PIN="${ROOT}/provenance/dotnet-runtime.env"

JAR="${1:?usage: gen_pal_java_contract.sh <pack.jar> [out-file]}"
OUT="${2:-${ROOT}/provenance/pal-java-contract.txt}"

[ -f "$JAR" ] || { echo "no such jar: $JAR" >&2; exit 1; }
command -v javap >/dev/null 2>&1 || {
    echo "javap not found; a JDK is required to read the PAL's Java contract" >&2
    echo "  (do not fall back to a hardcoded expectation -- that is the bug this" >&2
    echo "   script exists to remove)" >&2
    exit 1
}
# shellcheck disable=SC1090
[ -f "$PIN" ] && . "$PIN"

CLASSES="DotnetProxyTrustManager DotnetX509KeyManager PalPbkdf2"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
unzip -q -o "$JAR" -d "$WORK"

for cls in $CLASSES; do
    f="${WORK}/net/dot/android/crypto/${cls}.class"
    [ -f "$f" ] || { echo "  [FAIL] ${cls}.class not in the pack's jar" >&2; exit 1; }
done

{
    echo "# Java contract the pinned .NET crypto PAL expects."
    echo "#"
    echo "# Generated by scripts/gen_pal_java_contract.sh from the jar inside"
    echo "#   ${DOTNET_RUNTIME_PACK:-microsoft.netcore.app.runtime.android-arm64}"
    echo "#   ${DOTNET_RUNTIME_VERSION:-<unpinned>}"
    echo "# pinned in provenance/dotnet-runtime.env."
    echo "#"
    echo "# Do not edit by hand. After any runtime bump, re-run:"
    echo "#   ./scripts/fetch_dotnet_runtime.sh <out-dir>   # regenerates this file"
    echo "# verify_crypto_java.sh compares the Java sources against it. If a"
    echo "# descriptor here has no counterpart in the sources, the build fails."
    echo "#"
    echo "# <internal/class/name>\t<member>\t<descriptor>"

    for cls in $CLASSES; do
        f="${WORK}/net/dot/android/crypto/${cls}.class"
        # Only methods and constructors are part of the contract: the PAL never
        # looks a field up. javap renders a constructor with the fully-qualified
        # class name, so those become "<init>".
        javap -p -s "$f" 2>/dev/null |
            awk -v cls="${cls}" '
                /^  [^ ]/ {
                    sig = $0
                    sub(/^  /, "", sig)
                    if (index(sig, "(") == 0) { pending = ""; next }  # field / class line
                    sub(/;$/, "", sig)
                    sub(/[[:space:]]throws.*$/, "", sig)               # throws clause
                    if (sig !~ /\)$/) { pending = ""; next }           # still not a method
                    head = substr(sig, 1, index(sig, "(") - 1)
                    n = split(head, w, / +/)
                    name = w[n]
                    # javap prints a constructor fully qualified, so the last token
                    # of the head is already the class name for <init>.
                    if (name == "net.dot.android.crypto." cls) name = "<init>"
                    pending = (name != "" ? name : "")
                    next
                }
                /^    descriptor: / {
                    if (pending != "") {
                        d = $0
                        sub(/^    descriptor: /, "", d)
                        printf "net/dot/android/crypto/%s\t%s\t%s\n", cls, pending, d
                        pending = ""
                    }
                }
            ' | sort -u
    done
} > "$OUT"

ENTRIES="$(grep -vc '^#' "$OUT" || true)"
if [ "${ENTRIES:-0}" -eq 0 ]; then
    echo "  [FAIL] no members extracted from ${JAR}" >&2
    rm -f "$OUT"
    exit 1
fi

echo "  wrote ${OUT} (${ENTRIES} member descriptors)"
