#!/usr/bin/env bash
# ==============================================================================
# BepInEx Android - report whether the pinned .NET runtime is still current
# ==============================================================================
#
# WHAT THIS IS FOR
#
# fetch-runtime.yml runs weekly, and its comment says the run "exists to notice a
# new runtime and to re-attest the pin". It did not notice anything: it downloaded
# the pinned version, compared its SHA-256 against the pin, and stopped. There was
# no code anywhere that asked Microsoft what the current release was, so a new .NET
# runtime could ship and this repository would not find out until something failed.
#
# This script supplies the half that was missing. It reads the channel's current
# `latest-runtime` from Microsoft's official releases index and compares it to the
# pin.
#
# WHY IT REPORTS AND DOES NOT BUMP
#
# Bumping the runtime is a four-step coupled change, recorded at the top of
# provenance/dotnet-runtime.env:
#
#   1. DOTNET_RUNTIME_VERSION, DOTNET_RUNTIME_TFM, DOTNET_RUNTIME_EXPECTED_TFM and
#      DOTNET_RUNTIME_PACK_SHA256 in that file.
#   2. The matching tfm/version pair in scripts/package_bepinex_android.sh.
#   3. provenance/pal-java-contract.txt, regenerated from the new pack's own jar.
#   4. provenance/sha256sums.txt, regenerated by verify_prebuilts.sh.
#
# Step 3 is why this cannot be automated. The PAL resolves net.dot.android.crypto.*
# by name during JNI_OnLoad and aborts the process if a class is missing, so a
# contract generated against the wrong pack does not fail a build - it SIGABRTs on
# the device. A hardcoded expectation is worse than none: this repository shipped
# a build that passed its own gate and aborted on hardware because the expectation
# was .NET 11's signatures while the pack was .NET 10's.
#
# So this script exits 0 whether or not the runtime has moved. A newer runtime is
# news, not a defect, and failing the weekly job for it would be exactly the noise
# that teaches people to stop reading this job's output. The report goes to the
# step summary, where it is visible without opening the log.
# ==============================================================================
#
# USAGE
#   scripts/check_runtime_pin.sh
#
# Environment:
#   RELEASES_INDEX   override the metadata URL (tests)
#   GITHUB_STEP_SUMMARY   when set, the report is appended here as well as stdout

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

PIN_FILE="provenance/dotnet-runtime.env"
RELEASES_INDEX="${RELEASES_INDEX:-https://builds.dotnet.microsoft.com/dotnet/release-metadata/releases-index.json}"

echo "============================================================"
echo " .NET runtime pin report                                 "
echo "============================================================"

if [ ! -f "$PIN_FILE" ]; then
    echo "::error::${PIN_FILE} is missing; there is nothing to compare against"
    exit 1
fi

# Sourced, not grepped: the file is the pin, and reading it any other way means a
# second parser that can disagree with the one every build already uses.
set -a
# shellcheck disable=SC1090,SC1091
. "$PIN_FILE"
set +a

: "${DOTNET_RUNTIME_VERSION:?DOTNET_RUNTIME_VERSION missing from ${PIN_FILE}}"

# 10.0.12 -> 10.0, which is the channel-version key in the index.
CHANNEL="$(printf '%s' "$DOTNET_RUNTIME_VERSION" | cut -d. -f1,2)"
PREFIX="$(printf '%s' "$DOTNET_RUNTIME_VERSION" | cut -d. -f1)"

echo "  pin    : ${DOTNET_RUNTIME_VERSION}  (channel ${CHANNEL})"
echo "  source : ${RELEASES_INDEX}"

if ! index="$(curl -sSf --max-time 60 "$RELEASES_INDEX")"; then
    # A metadata outage is not a runtime finding. Report it and stop: claiming
    # "current" because the check could not run would be the fail-open shape this
    # repository keeps removing.
    echo "::warning::could not read the releases index"
    echo "::warning::runtime currency unknown - nothing is being claimed either way"
    echo "This is a metadata outage, not a runtime finding."
    exit 0
fi

# Parse with python rather than grep: the index is nested, and a grep for
# "latest-runtime" would happily match a different channel's entry.
#
# The status token comes FIRST and is checked on its own, before any value is
# interpreted. The first version of this emitted the status in the same column as
# the data and then read it out of the wrong field, so a malformed index was
# reported as "a newer runtime exists" - the exact fail-open this script exists to
# avoid, caught by scripts/test_runtime_pin.sh on its first run.
read -r FINDING LATEST_SDK LATEST_RUNTIME SUPPORT <<EOF
$(printf '%s' "$index" | python3 -c "
import json, sys
try:
    d = json.load(sys.stdin)
    assert isinstance(d, dict) and 'releases-index' in d, 'no releases-index key'
except Exception as e:
    print('UNREADABLE\t?\t?\t?')
    sys.exit(0)
for e in d['releases-index']:
    cv = e.get('channel-version', '')
    if cv == '${CHANNEL}' or cv.split('.')[0] == '${PREFIX}':
        print('FOUND\t%s\t%s\t%s' % (e.get('latest-sdk', '?'),
                                     e.get('latest-runtime', '?'),
                                     e.get('support-phase', '?')))
        break
else:
    print('NO_CHANNEL\t?\t?\t?')
")
EOF

case "$FINDING" in
FOUND) ;;
UNREADABLE)
    echo "::warning::the releases index could not be read or parsed"
    echo "::warning::runtime currency unknown - nothing is being claimed either way"
    exit 0
    ;;
NO_CHANNEL)
    echo "::warning::no channel ${CHANNEL} (or any ${PREFIX}.x) in the releases index"
    echo "::warning::runtime currency unknown - nothing is being claimed either way"
    exit 0
    ;;
*)
    echo "::error::unexpected finding '${FINDING}' from the metadata parser"
    exit 1
    ;;
esac

echo "  latest : ${LATEST_RUNTIME}  (sdk ${LATEST_SDK}, ${SUPPORT})"

STATUS="current"
if [ "$LATEST_RUNTIME" != "$DOTNET_RUNTIME_VERSION" ]; then
    STATUS="moved"
fi

echo ""
echo "============================================================"
echo " RESULT: ${STATUS} - pin ${DOTNET_RUNTIME_VERSION}, channel is on ${LATEST_RUNTIME}"
echo "============================================================"

if [ "$STATUS" = "moved" ]; then
    # Say what to do, not just that something changed. The procedure is the one
    # recorded in the pin file, and repeating it here means the reader does not
    # have to go looking for it while deciding whether this matters.
    cat <<EOF

A newer runtime is available. This is not a failure and nothing here has been
changed. Bumping it is deliberate work, and the four coupled steps are recorded at
the top of ${PIN_FILE}:

  1. DOTNET_RUNTIME_VERSION / _TFM / _EXPECTED_TFM / _PACK_SHA256 in ${PIN_FILE}.
  2. The matching tfm/version pair in scripts/package_bepinex_android.sh.
  3. provenance/pal-java-contract.txt, regenerated from the new pack's own jar by
     scripts/fetch_dotnet_runtime.sh. Not optional and not hand-written: the PAL
     resolves net.dot.android.crypto.* by name during JNI_OnLoad and aborts the
     process if a class is missing, so a contract that does not match the pack
     passes every build check and fails on the device.
  4. provenance/sha256sums.txt, via
     launcher/scripts/verify_prebuilts.sh --update-manifest.

Step 3 is the reason this script does not open a PR for you.

Before starting, check whether the new runtime is compatible at all: MonoMod.Core's
runtime dispatch is a switch on the major version whose cases stop at 10 and whose
default branch throws PlatformNotSupportedException, so a runtime beyond .NET 10
would refuse to run every Harmony patch on device. That is why the pin is on 10.
EOF
fi

# Also surface it in the run summary, where a weekly run's result is actually read.
if [ -n "${GITHUB_STEP_SUMMARY:-}" ]; then
    {
        echo "### .NET runtime pin"
        echo ""
        echo "| | |"
        echo "|---|---|"
        echo "| pinned | \`${DOTNET_RUNTIME_VERSION}\` |"
        echo "| channel latest | \`${LATEST_RUNTIME}\` |"
        echo "| channel SDK | \`${LATEST_SDK}\` |"
        echo "| support phase | ${SUPPORT} |"
        echo "| status | **${STATUS}** |"
        echo ""
        if [ "$STATUS" = "moved" ]; then
            echo "A newer runtime is published. The four coupled steps are at the top of"
            echo "\`${PIN_FILE}\`. Nothing was changed automatically, and step 3 is not"
            echo "automatable: a PAL Java contract that does not match the pack passes"
            echo "every build check and aborts on the device."
        fi
    } >>"$GITHUB_STEP_SUMMARY"
fi